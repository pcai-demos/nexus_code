// Parser for file operations extracted from LLM text
function parseFileOperations(responseText, ideState, intent) {
  const operations = [];
  const seenPaths = new Set();
  const fencedRanges = [];

  const codeBlockRegex = /```(\w*)\n([\s\S]*?)```/g;
  let match;

  while ((match = codeBlockRegex.exec(responseText)) !== null) {
    const language = match[1] || "plaintext";
    const codeContent = match[2];
    fencedRanges.push({ start: match.index, end: match.index + match[0].length });

    const filePathMatch = codeContent.match(/^(?:#|\/\/)\s*File:\s*(.+?)(?:\n|$)/m);
    if (filePathMatch) {
      const filePath = filePathMatch[1].trim();
      if (!seenPaths.has(filePath)) {
        const cleanContent = codeContent.replace(/^(?:#|\/\/)\s*File:\s*.+?\n/m, "").trim();
        operations.push({
          type: "writeFile",
          path: filePath,
          content: cleanContent + "\n",
          language,
        });
        seenPaths.add(filePath);
      }
      continue;
    }

    const precedingText = responseText.slice(Math.max(0, match.index - 200), match.index);
    const precedingFileMatch = precedingText.match(/(?:#|\/\/)\s*File:\s*(.+?)[\s]*$/m);
    if (precedingFileMatch) {
      const filePath = precedingFileMatch[1].trim();
      if (!seenPaths.has(filePath)) {
        operations.push({
          type: "writeFile",
          path: filePath,
          content: codeContent.trim() + "\n",
          language,
        });
        seenPaths.add(filePath);
      }
      continue;
    }
  }

  return operations;
}

/**
 * T28's whole-document read (region 2c, design D5), moved into ONE function both whole-document paths call — T63
 * (t63-design.md §2.2): an enumeration reads after retrieval (its scope may be the vote's), a lookup whose document
 * the request selected reads BEFORE retrieval (its scope is the request's). Whole documents in the given order while
 * they fit the budget; a document that does not fit is never cut — unread and named. Complete only when MEASURED
 * complete: every stored chunk read and the measured size within the remaining budget (T13: measured, never
 * claimed). Throws on a store error — the caller's try decides what that costs (F-25).
 */
async function readDocumentsWhole({ documents, budgetTokens, client }) {
  const plan = planDocumentReads({
    documents,
    budgetTokens,
    meanCharsPerChunk: CONTEXT_ASSEMBLY_CONSTANTS.MEAN_CHARS_PER_CHUNK,
    charsPerToken: CONTEXT_ASSEMBLY_CONSTANTS.CHARS_PER_TOKEN,
    headerCharsPerBlock: CONTEXT_ASSEMBLY_CONSTANTS.HEADER_CHARS_PER_BLOCK,
  });
  const readStart = Date.now();
  const reads = [];
  let rows = [];
  let usedTokens = 0;
  for (const doc of plan.read) {
    const docRows = await client.fetchDocumentChunks({
      source: doc.source,
      // A ranked chunk's sourceId when one was ranked, else the
      // summary's (a request / named document may have none ranked).
      sourceId: doc.sourceId || (Array.isArray(doc.sourceIds) && doc.sourceIds.length === 1 ? doc.sourceIds[0] : null),
      limit: (doc.chunkCount || 0) + 50,
    });
    const ordered = orderDocument(docRows);
    const chars = ordered.reduce((a, r) => a + String(r.text || "").length, 0);
    const post = budgetFor({
      document: doc,
      chars,
      rows: ordered.length,
      budgetTokens: Math.max(1, budgetTokens - usedTokens),
      charsPerToken: CONTEXT_ASSEMBLY_CONSTANTS.CHARS_PER_TOKEN,
      headerCharsPerBlock: CONTEXT_ASSEMBLY_CONSTANTS.HEADER_CHARS_PER_BLOCK,
    });
    // Complete only when MEASURED complete: every stored chunk read (the
    // summary's count) and the measured size within the remaining budget.
    const complete = post.fits && Number.isFinite(doc.chunkCount) && ordered.length >= doc.chunkCount;
    reads.push({
      source: doc.source,
      coverage: complete ? "complete" : "partial",
      partialCause: complete ? null : post.fits ? "incomplete-read" : "budget",
      chunksRead: ordered.length,
      chunksInStore: doc.chunkCount,
      pages: doc.totalPages,
      estimatedTokens: post.estimatedTokens,
    });
    if (complete) {
      rows = rows.concat(ordered);
      usedTokens += post.estimatedTokens || 0;
    }
  }
  const readMs = Date.now() - readStart;
  const completeReads = reads.filter((r) => r.coverage === "complete");
  const out = {
    unread: plan.unread,
    reads,
    rows,
    readMs,
    chunksRead: reads.reduce((a, r) => a + (r.chunksRead || 0), 0),
    estimatedTokens: reads.reduce((a, r) => a + (r.estimatedTokens || 0), 0) + plan.unread.reduce((a, u) => a + (u.estimatedTokens || 0), 0),
    pagesRead: null,
    coverage: "partial",
    partialCause: null,
  };
  if (rows.length > 0) {
    out.pagesRead = [...new Set(rows.map((r) => Number(r.page)).filter((p) => Number.isInteger(p) && p > 0))].sort((a, b) => a - b);
    // COMPLETE only when EVERY in-scope document was read whole (D5).
    out.coverage = completeReads.length === documents.length ? "complete" : "partial";
    out.partialCause = out.coverage === "complete" ? null : plan.unread.length > 0 ? "budget" : "incomplete-read";
  } else {
    out.partialCause = reads.some((r) => r.partialCause === "incomplete-read") ? "incomplete-read" : "budget";
  }
  return out;
}

