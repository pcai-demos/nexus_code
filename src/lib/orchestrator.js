// Helper to write files into workspace
function writeWorkspaceFile(filename, content) {
  try {
    // E2 (CA-001, 2026-10-06; the one coding-owned hunk of this file): the model's `# File:` path is contained
    // under the workspace root before any directory is made — the same three checks as src/lib/coding/paths.js
    // resolveInside (an import cannot be added outside these lines): no absolute path, no `..` segment, and the
    // resolved path strictly inside the root; a refused path is logged and skipped, nothing is written.
    const rel = String(filename).replace(/\\/g, "/");
    const rootAbs = path.resolve(WORKSPACE_ROOT);
    const filePath = path.resolve(rootAbs, rel);
    if (path.posix.isAbsolute(rel) || /^[A-Za-z]:/.test(rel) || rel.split("/").includes("..") || !filePath.startsWith(rootAbs + path.sep)) {
      console.warn(`[Orchestrator Sync] Refused a write outside the workspace: ${JSON.stringify(filename)}`);
      return;
    }
    const dir = path.dirname(filePath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(filePath, content, "utf-8");
    console.log(`[Orchestrator Sync] Automatically wrote file to IDE workspace: ${filename}`);
  } catch (err) {
    console.error(`[Orchestrator Sync] Failed to write file: ${err.message}`);
  }
}

/**
 * Maximal Marginal Relevance (MMR) page/section diversity filter — prevents
 * duplicate disclaimers from crowding out distinct pages.
 *
 * Extracted in T12 so it can run inside its own try block. It is a reordering
 * of results that have ALREADY been retrieved successfully, so if it throws the
 * caller keeps the raw results (F-25: post-retrieval bookkeeping used to sit
 * inside the same catch as retrieval, which turned any bug in here into a
 * silent "no context found").
 */
function applyPageDiversity(rawResults, perPageLimit) {
  const diverseChunks = [];
  const pageChunkCount = {};

  // Pass 1: Hydrate isVisualElement from metadata JSON, then prioritize visual elements
  for (let c of rawResults) {
    // Hydrate isVisualElement from metadata JSON (not stored as a top-level Weaviate property yet)
    try {
      const meta = JSON.parse(c.metadata || "{}");
      if (meta.isVisualElement) c.isVisualElement = true;
    } catch (e) {}

    const pageKey = `${c.source || 'doc'}_page_${c.page || 1}`;
    pageChunkCount[pageKey] = (pageChunkCount[pageKey] || 0);

    if (c.isVisualElement || pageChunkCount[pageKey] < perPageLimit) {
      diverseChunks.push(c);
      pageChunkCount[pageKey]++;
    }
  }

  // Pass 2: Fill remaining budget with secondary chunks
  for (let c of rawResults) {
    if (!diverseChunks.includes(c)) {
      diverseChunks.push(c);
    }
  }

  return diverseChunks;
}

// Programmatic Compliance Auditor
function auditCodeCompliance(code, retrievedChunks) {
  const violations = [];
  const lowercaseCode = code.toLowerCase();
  
  const hasReconciliationRules = retrievedChunks.some(c => 
    c.text.toLowerCase().includes("reconciliation") || 
    c.source.toLowerCase().includes("reconciliation") ||
    c.text.toLowerCase().includes("sysc 15.1")
  );
  if (hasReconciliationRules) {
    if (lowercaseCode.includes("float") || (lowercaseCode.includes("/") && !lowercaseCode.includes("decimal"))) {
      violations.push("Violation of REQ-MATH-01 (FCA SYSC 15.1 / PSRs Regulation 84): Floating-point math detected. Financial reconciliation systems must use Python's native decimal.Decimal library to achieve exact parity.");
    }
  }

  const hasAmlRules = retrievedChunks.some(c => 
    c.text.toLowerCase().includes("aml") || 
    c.text.toLowerCase().includes("screening") || 
    c.source.toLowerCase().includes("compliance_standards")
  );
  if (hasAmlRules) {
    if (lowercaseCode.includes("payment") && !lowercaseCode.includes("screen_parties")) {
      violations.push("Violation of AML Compliance Mandates: Transaction execution flow does not execute screening checks via '_screen_parties()' prior to routing.");
    }
  }

  const hasIntegrityRules = retrievedChunks.some(c => 
    c.text.toLowerCase().includes("integrity") || 
    c.text.toLowerCase().includes("hash")
  );
  if (hasIntegrityRules) {
    if (lowercaseCode.includes("payload") && !lowercaseCode.includes("hash") && !lowercaseCode.includes("sha256")) {
      violations.push("Violation of PCI-DSS Integrity Guidelines: Payload transmission lacks structural integrity hashes (_generate_integrity_hash or cryptographic verification).");
    }
  }

  const hasResilienceRules = retrievedChunks.some(c => 
    c.text.toLowerCase().includes("resilience") || 
    c.text.toLowerCase().includes("retry")
  );
  if (hasResilienceRules) {
    if (lowercaseCode.includes("network") && !lowercaseCode.includes("retry") && !lowercaseCode.includes("backoff")) {
      violations.push("Violation of Operational Resilience Guidelines: Network outbound request is missing retry mechanisms and exponential backoff wrappers (_execute_network_call_with_retry).");
    }
  }

  return violations;
}

