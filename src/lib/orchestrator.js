  // the turn's scope, because the Turn Scope span (built after the retrieval
  // block) reads it too (A5: a block-scoped `let` cost every retrieving turn
  // its Turn Scope span on the first T30 image).
  let followUpQuery = { query: "", applied: false, reason: "not evaluated", cue: null, previousScope: null };
  // T65 (t65-design.md §11b): the census of the question's names — declared HERE, at the turn's scope, for T30's A5
