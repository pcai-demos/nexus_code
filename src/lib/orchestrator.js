  const route = routeTurn({
    message,
    forcedCommand: adminConfig?.forcedCommand ?? null,
    ideState,
    contextDefaults: resolveContextConfig(adminConfig?.ragSettings),
    // T30 (design D3): the history is read by the router for the follow-up
    // verdict — the only place the retrieval side reads it.
    history,
  });
  const agentMode = route.mode; // "chat" | "doc" | "code"
