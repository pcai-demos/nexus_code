      // T63 (t63-design.md §2.1–§2.2; D2 (a), D3 (a), D4 (a), D8 (a)): a LOOKUP whose document the REQUEST selected,
      // within the budget, reads that document whole BEFORE retrieval — region 2c's read, the one function both paths
      // call. Only a COMPLETE read skips the reranker: every passage is then in the prompt, and the design's capture
      // found the prompt byte-identical without it (27 of 27 turns). The search still runs, so the trace shows what it
      // found and the retrieval state keeps its meaning (T12). A read that does not complete — a store error, fewer
