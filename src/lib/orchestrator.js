          // the store's env override or the workload identity, as it did there.
          const countClient = new WeaviateClient(rc.weaviateUrl, resolveCredential({ url: rc.weaviateUrl, requestValue: rc.weaviateToken || rc.token }).value, rc.weaviateCollection);
