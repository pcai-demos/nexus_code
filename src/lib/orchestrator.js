  // which is why four causes collapsed into one answer:
  //
  //   "failed"    retrieval did not happen. Nothing is known about the corpus,
  //               so claiming the documents lack content is a fabrication.
  //   "empty"     retrieval happened and legitimately found nothing above the
  //               relevance floor (possible only since T08). This is the ONLY
  //               state in which "the document doesn't mention it" is honest.
  //   "degraded"  results are real but a stage that shapes their quality did
  //               not run, so they may include irrelevant passages.
  //   "ok"        results are real and were ranked.
  //   "skipped"   chat mode; retrieval was never attempted (so that T13 does
  //               not read a conversational turn as a retrieval failure).
  let retrieval = { state: "skipped", code: null, message: null, chunkCount: 0 };
  // T23: the credential sources the retrieve route reported for this turn
  // (its report lives in the RAG trace's details; captured here for the
  // response). Null until retrieval reports, and null when it fails first.
  let retrievalCredentialSources = null;
  // T28: the assembly knobs for this turn, through the one config module.
  const assemblyConfig = resolveContextConfig(adminConfig?.ragSettings);
  // T28: what region 2b (the page read) and 2c (the document scope)
  // measured — null until they run; chat mode, the aggregation path, code
  // mode and a failed retrieval leave them null ("did not run" is not
  // "added 0"). `contextAssembly` is filled at prompt assembly.
  let companionState = null;
  let documentContext = null;
  let contextAssembly = null;
  // T63 (t63-design.md §2.1–§2.2): the lookup gate's verdict (planLookupRead — null on a turn that never reached it)
  // and, when it held, the whole read taken BEFORE retrieval. A completed read skips the reranker and becomes region
  // 2c's document; one that did not complete leaves the turn on today's ranked path (D8 (a)).
  let lookupPlan = null;
  let lookupRead = null;
  let rerankSkippedForWholeRead = false;
  // T48 (design §2.1, §2.4): the computed context notes this turn's context carried — null when no numbered context
  // was built (the aggregation path, nothing retrieved); the response's answerPolicy and the assembly span name them.
  let contextNotesReport = null;
  // T53 (t53-design.md §1, D5 (a)): the noted chain blocks whose NOT PRINTED line names an edge — [{ marker, text }],
  // each block's [S#] marker and its stored chunk text — kept at the notes seam for the record-only check after the
