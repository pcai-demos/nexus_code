      // log, no signal. That silent fall-through, not the catch, is the path
      // that produced "the document doesn't mention it" for indexed content.
      // ───────────────────────────────────────────────────────────────────
      let rawResults = [];
      let degradations = [];
      // T13: the route's measured retrieval report (pool depth, floor, score
      // shape), forwarded verbatim into the trace. null when retrieval failed —
      // no search ran, so a report of zeros would be a fabricated measurement
      // of work that did not happen (E31).
      let retrievalReport = null;
