      // depends on the intent: enumerationScope for an enumeration turn,
      // lookupScope otherwise; a count question is never scoped (T09).
      const scopeKnob = isMultiEntityQuery ? assemblyConfig.enumerationScope : assemblyConfig.lookupScope;
      let preScope = null;
      // T65 (t65-design.md D2 (a), D3 (a)): the store's census of the names the question carries — which documents'
      // text holds each — read before retrieval, so a name only one document holds (or the one document holding every
      // name) selects it as the request's selection does. Only where a selection could apply: a scope knob on, not a
      // count, no document the request selected. A failure costs the signal, never the turn (F-25).
      const requestSelects = (Array.isArray(documentScope) ? documentScope : typeof documentScope === "string" && documentScope ? [documentScope] : []).some((s) => dbSummaryDetails.some((d) => d && d.source === s));
      if (scopeKnob !== "off" && !targetAggregationKeyword && !requestSelects && summaryClient) {
        try {
          nameCensus.names = questionNames(cleanQuery);
          if (nameCensus.names.length > 0) {
            const censusStart = Date.now();
            nameHolders = await summaryClient.documentsHolding(nameCensus.names);
            nameCensus.ms = Date.now() - censusStart;
            nameCensus.holders = nameHolders;
          }
        } catch (err) {
          console.error("[Orchestrate RAG Bookkeeping Error - name census]:", err.message);
          nameCensus.error = err.message;
          nameHolders = null;
        }
      }
      if (scopeKnob !== "off" && !targetAggregationKeyword) {
        try {
          preScope = resolveTurnScope({ message: cleanQuery, ranked: [], summary: dbSummaryDetails, requestScope: documentScope, threshold: CONTEXT_ASSEMBLY_CONSTANTS.SCOPE_DOMINANCE_SHARE, nameHolders });
        } catch (err) {
          console.error("[Orchestrate RAG Bookkeeping Error - pre-scope]:", err.message);
          bookkeepingError = bookkeepingError || { code: CODES.BOOKKEEPING_FAILED, stage: "pre-scope", message: err.message };
          preScope = null;
        }
      }
      const preScopeFilter =
        preScope && preScope.prefilter && preScope.documents.length > 0
          ? { sourceIds: preScope.documents.flatMap((d) => (Array.isArray(d.sourceIds) ? d.sourceIds : [])), sources: preScope.documents.map((d) => d.source) }
          : null;

