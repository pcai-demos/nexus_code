      // Region 1 of 3 — RETRIEVAL. Only what can genuinely fail retrieval is
      // inside this block. Everything after it describes work that already
      // succeeded (F-25).
      //
      // Note that failure here is mostly NOT an exception: a dead embedding
      // endpoint returns a clean HTTP 500, and pre-T12 `if (retrieveRes.ok)`
